#!/usr/bin/env python3
"""Generate .cursor/agents/*.md from Agents/Subagents/ per Agents/Setup/cursor-agents.json."""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

HUB_ROOT = Path(__file__).resolve().parents[3]
SUBAGENTS_DIR = HUB_ROOT / "Agents" / "Subagents"
MANIFEST = HUB_ROOT / "Agents" / "Setup" / "cursor-agents.json"
OUT_DIR = HUB_ROOT / ".cursor" / "agents"
GENERATOR = "Agents/Setup/scripts/sync-cursor-agents.sh"


def split_frontmatter(text: str) -> tuple[dict[str, str], str]:
    if not text.startswith("---"):
        raise ValueError("missing frontmatter")
    match = re.match(r"^---\r?\n(.*?)\r?\n---\r?\n?", text, re.DOTALL)
    if not match:
        raise ValueError("unclosed frontmatter")
    raw_fm, body = match.group(1), text[match.end() :]
    fields: dict[str, str] = {}
    for line in raw_fm.splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        if ":" not in line:
            continue
        key, val = line.split(":", 1)
        fields[key.strip()] = val.strip()
    return fields, body.lstrip("\n")


def yaml_quote(s: str) -> str:
    if re.search(r'[:#\n"\\]', s) or s.startswith(("-", "?", "|", ">", "@", "`")):
        escaped = s.replace("\\", "\\\\").replace('"', '\\"')
        return f'"{escaped}"'
    return s


def build_cursor_file(
    name: str, description: str, readonly: bool, source_rel: str, body: str
) -> str:
    ro = "true" if readonly else "false"
    header = (
        f"<!-- Generated by {GENERATOR}. "
        f"Edit {source_rel} and re-run sync. -->\n\n"
    )
    fm = (
        "---\n"
        f"name: {name}\n"
        f"description: {yaml_quote(description)}\n"
        "model: inherit\n"
        f"readonly: {ro}\n"
        "---\n\n"
    )
    return fm + header + body


def main() -> int:
    if not MANIFEST.is_file():
        print(f"manifest not found: {MANIFEST}", file=sys.stderr)
        return 1

    manifest = json.loads(MANIFEST.read_text(encoding="utf-8"))
    agents = manifest.get("agents", [])
    OUT_DIR.mkdir(parents=True, exist_ok=True)

    expected_names = {a["name"] for a in agents}
    for existing in OUT_DIR.glob("*.md"):
        if existing.stem not in expected_names:
            existing.unlink()
            print(f"removed stale {existing.relative_to(HUB_ROOT)}")

    for entry in agents:
        name = entry["name"]
        source = entry["source"]
        readonly = bool(entry.get("readonly", False))
        src_path = SUBAGENTS_DIR / source
        if not src_path.is_file():
            print(f"missing source: {src_path}", file=sys.stderr)
            return 1

        fields, body = split_frontmatter(src_path.read_text(encoding="utf-8"))
        hub_name = fields.get("name", name)
        if hub_name != name:
            print(
                f"warning: manifest name {name} != frontmatter name {hub_name} in {source}",
                file=sys.stderr,
            )
        description = fields.get("description", "").strip()
        if not description:
            print(f"missing description in {source}", file=sys.stderr)
            return 1

        source_rel = f"Agents/Subagents/{source}"
        out_text = build_cursor_file(name, description, readonly, source_rel, body)
        out_path = OUT_DIR / f"{name}.md"
        out_path.write_text(out_text, encoding="utf-8")
        print(f"wrote {out_path.relative_to(HUB_ROOT)}")

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
